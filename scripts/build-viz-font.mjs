/**
 * Regenerates lib/viz-font.ts, the app font embedded in visualisation frames.
 *
 * Visualisations run in a sandboxed frame whose policy allows fonts only from
 * data: URLs, so the frame cannot load the font file the app itself uses. This
 * embeds the Latin variable-weight Instrument Sans file as base64. Run it after
 * upgrading @fontsource-variable/instrument-sans:
 *
 *   node scripts/build-viz-font.mjs
 */
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"

const require = createRequire(import.meta.url)
const file = require.resolve(
  "@fontsource-variable/instrument-sans/files/instrument-sans-latin-wght-normal.woff2"
)
const base64 = readFileSync(file).toString("base64")
const output = new URL("../lib/viz-font.ts", import.meta.url)

writeFileSync(
  output,
  `/**
 * Generated by scripts/build-viz-font.mjs from @fontsource-variable/instrument-sans
 * (SIL Open Font License 1.1). Do not edit by hand.
 *
 * The app font's Latin variable-weight file as a data URL, so visualisation
 * frames, which may load fonts only from data: URLs, use the same type as the app.
 */
export const VIZ_FONT_DATA_URL =
  "data:font/woff2;base64,${base64}"
`
)
console.log(`Wrote ${output.pathname} (${base64.length} base64 characters)`)
